// Command fakerancher runs three fake Rancher sites on localhost for manual
// testing of the portal, and writes a matching portal config.
//
//	go run ./cmd/fakerancher
//	go run ./cmd/portal -config dev/config.yaml
//
// Test users (all sites unless noted):
//
//	admin1 / pass1   accepted everywhere
//	drift  / pass1   accepted on site-1 and site-3; site-2 expects "other"
//	nopr   / pass1   no activedirectory_user principal (warning path)
//	limited / pass1  accepted everywhere; denied kagent access on every prod cluster
//
// Each site serves 41 clusters: "local" (the portal drops it) and 40 named
// <site>-<env>-<nn> (envs prod, stg, dev), paginated 25 per page. Of those,
// 3 are disconnected, one answers the agent card with 404, one with 503, and
// one hangs for 30s (the portal's api timeout is 5s here, so it shows as
// unreachable).
//
// Ready clusters stream a scripted A2A chat reply with 300ms between events.
// Per site, five more clusters misbehave in chat: n=20 stays silent for 20s
// before answering, n=22 sends a JSON-RPC error, n=23 ends with state failed,
// n=25 never sends anything (hang), n=26 stops after "working" with no final
// event (cut off).
package main

import (
	"flag"
	"fmt"
	"log"
	"os"
	"os/signal"
	"path/filepath"
	"syscall"
	"time"

	"github.com/jhyoong/RANK-proxy-webapp/internal/rancher/ranchertest"
)

const dn = "activedirectory_user://CN=Test Admin (Admin), OU=Example Admins,OU=Example Org,DC=example,DC=com"

func main() {
	dir := flag.String("dir", "dev", "directory for CA files and the generated portal config")
	basePort := flag.Int("base-port", 9441, "first port; sites use base-port, +1, +2")
	flag.Parse()

	if err := os.MkdirAll(*dir, 0o700); err != nil {
		log.Fatal(err)
	}
	cfg := "# Generated by cmd/fakerancher. Local testing only.\nlisten: 127.0.0.1:8080\ncookie_secure: false\n" +
		"session:\n  idle_timeout: 2m\n  absolute_timeout: 1h\nlogin:\n  timeout: 5s\n" +
		"kagent:\n  agent_name: test-agent\napi:\n  timeout: 5s\n" +
		"chat:\n  idle_timeout: 30s\n  heartbeat: 5s\n  log_events: true\nsites:\n"
	for i := 1; i <= 3; i++ {
		name := fmt.Sprintf("site-%d", i)
		users := map[string]ranchertest.FakeUser{
			"admin1":  {Password: "pass1", ID: fmt.Sprintf("u-admin1-s%d", i), PrincipalIDs: []string{"local://u-admin1", dn}},
			"drift":   {Password: "pass1", ID: "u-drift", PrincipalIDs: []string{dn}},
			"nopr":    {Password: "pass1", ID: "u-nopr", PrincipalIDs: []string{"local://u-nopr"}},
			"limited": {Password: "pass1", ID: "u-limited", PrincipalIDs: []string{"local://u-limited", dn}},
		}
		if i == 2 {
			users["drift"] = ranchertest.FakeUser{Password: "other", ID: "u-drift", PrincipalIDs: []string{dn}}
		}
		f := &ranchertest.Fake{Users: users, Clusters: seedClusters(name), PageSize: 25, Log: func(format string, args ...any) {
			log.Printf("["+name+"] "+format, args...)
		}}
		srv, err := ranchertest.StartTLS(f, fmt.Sprintf("127.0.0.1:%d", *basePort+i-1))
		if err != nil {
			log.Fatal(err)
		}
		defer srv.Close()
		ca, err := filepath.Abs(filepath.Join(*dir, "ca-"+name+".pem"))
		if err != nil {
			log.Fatal(err)
		}
		if err := ranchertest.WriteCA(srv, ca); err != nil {
			log.Fatal(err)
		}
		cfg += fmt.Sprintf("  - name: %s\n    url: %s\n    ca_file: %s\n", name, srv.URL, ca)
		log.Printf("[%s] listening on %s", name, srv.URL)
	}
	cfgPath := filepath.Join(*dir, "config.yaml")
	if err := os.WriteFile(cfgPath, []byte(cfg), 0o600); err != nil {
		log.Fatal(err)
	}
	log.Printf("wrote %s; now run: go run ./cmd/portal -config %s  (then open http://127.0.0.1:8080)", cfgPath, cfgPath)
	log.Printf("users: admin1/pass1 (all ok), drift/pass1 (site-2 rejects), nopr/pass1 (no AD principal), limited/pass1 (no-access on prod clusters)")
	log.Printf("chat: ready clusters stream at 300ms/step; per site n=20 silent 20s gap, n=22 JSON-RPC error, n=23 failed, n=25 hang, n=26 cut off")

	sig := make(chan os.Signal, 1)
	signal.Notify(sig, os.Interrupt, syscall.SIGTERM)
	<-sig
}

// seedClusters returns the fake clusters for one site: "local" plus 40 named
// <site>-<env>-<nn>, with a few deliberately broken ones.
func seedClusters(site string) []ranchertest.FakeCluster {
	envs := []string{"prod", "stg", "dev"}
	connected := []ranchertest.Condition{
		{Type: "Connected", Status: "True"},
		{Type: "Ready", Status: "True"},
	}
	cs := []ranchertest.FakeCluster{{ID: "local", DisplayName: "local", State: "active", Conditions: connected}}
	for n := 1; n <= 40; n++ {
		env := envs[(n-1)%len(envs)]
		name := fmt.Sprintf("%s-%s-%02d", site, env, n)
		c := ranchertest.FakeCluster{ID: "c-" + name, DisplayName: name, State: "active", Conditions: connected}
		switch n {
		case 5, 17, 29:
			c.State = "unavailable"
			c.Conditions = []ranchertest.Condition{{Type: "Connected", Status: "False", Reason: "Disconnected"}}
		case 8:
			c.CardStatus = 404
		case 11:
			c.CardStatus = 503
		case 14:
			c.CardDelay = 30 * time.Second
		}
		switch n {
		case 20:
			steps := slowChat()
			steps[len(steps)-3].Delay = 20 * time.Second
			c.ChatSteps = steps
		case 22:
			c.ChatSteps = []ranchertest.Step{{Delay: 300 * time.Millisecond,
				Data: `{"jsonrpc":"2.0","id":"1","error":{"code":-32000,"message":"model backend unavailable"}}`}}
		case 23:
			c.ChatSteps = append(slowChat()[:2], ranchertest.Step{Delay: 300 * time.Millisecond,
				Data: `{"jsonrpc":"2.0","id":"1","result":{"kind":"status-update","taskId":"t1","contextId":"c","final":true,"status":{"state":"failed"}}}`})
		case 25:
			c.ChatHang = true
		case 26:
			c.ChatSteps = slowChat()[:2]
		default:
			c.ChatSteps = slowChat()
		}
		if env == "prod" {
			c.Deny = map[string]bool{"limited": true}
		}
		cs = append(cs, c)
	}
	return cs
}

// slowChat is the default chat script with 300ms between events, so streaming
// is visible in the browser.
func slowChat() []ranchertest.Step {
	steps := ranchertest.DefaultChat()
	for i := range steps {
		steps[i].Delay = 300 * time.Millisecond
	}
	return steps
}
