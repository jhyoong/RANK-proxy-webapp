// Command fakerancher runs three fake Rancher sites on localhost for manual
// testing of the portal, and writes a matching portal config.
//
//	go run ./cmd/fakerancher
//	go run ./cmd/portal -config dev/config.yaml
//
// Test users (all sites unless noted):
//
//	admin1 / pass1   accepted everywhere
//	drift  / pass1   accepted on site-1 and site-3; site-2 expects "other"
//	nopr   / pass1   no activedirectory_user principal (warning path)
package main

import (
	"flag"
	"fmt"
	"log"
	"os"
	"os/signal"
	"path/filepath"
	"syscall"

	"github.com/jhyoong/RANK-proxy-webapp/internal/rancher/ranchertest"
)

const dn = "activedirectory_user://CN=Test Admin (Admin), OU=Example Admins,OU=Example Org,DC=example,DC=com"

func main() {
	dir := flag.String("dir", "dev", "directory for CA files and the generated portal config")
	basePort := flag.Int("base-port", 9441, "first port; sites use base-port, +1, +2")
	flag.Parse()

	if err := os.MkdirAll(*dir, 0o700); err != nil {
		log.Fatal(err)
	}
	cfg := "# Generated by cmd/fakerancher. Local testing only.\nlisten: 127.0.0.1:8080\ncookie_secure: false\n" +
		"session:\n  idle_timeout: 2m\n  absolute_timeout: 1h\nlogin:\n  timeout: 5s\nsites:\n"
	for i := 1; i <= 3; i++ {
		name := fmt.Sprintf("site-%d", i)
		users := map[string]ranchertest.FakeUser{
			"admin1": {Password: "pass1", ID: fmt.Sprintf("u-admin1-s%d", i), PrincipalIDs: []string{"local://u-admin1", dn}},
			"drift":  {Password: "pass1", ID: "u-drift", PrincipalIDs: []string{dn}},
			"nopr":   {Password: "pass1", ID: "u-nopr", PrincipalIDs: []string{"local://u-nopr"}},
		}
		if i == 2 {
			users["drift"] = ranchertest.FakeUser{Password: "other", ID: "u-drift", PrincipalIDs: []string{dn}}
		}
		f := &ranchertest.Fake{Users: users, Log: func(format string, args ...any) {
			log.Printf("["+name+"] "+format, args...)
		}}
		srv, err := ranchertest.StartTLS(f, fmt.Sprintf("127.0.0.1:%d", *basePort+i-1))
		if err != nil {
			log.Fatal(err)
		}
		defer srv.Close()
		ca, err := filepath.Abs(filepath.Join(*dir, "ca-"+name+".pem"))
		if err != nil {
			log.Fatal(err)
		}
		if err := ranchertest.WriteCA(srv, ca); err != nil {
			log.Fatal(err)
		}
		cfg += fmt.Sprintf("  - name: %s\n    url: %s\n    ca_file: %s\n", name, srv.URL, ca)
		log.Printf("[%s] listening on %s", name, srv.URL)
	}
	cfgPath := filepath.Join(*dir, "config.yaml")
	if err := os.WriteFile(cfgPath, []byte(cfg), 0o600); err != nil {
		log.Fatal(err)
	}
	log.Printf("wrote %s; now run: go run ./cmd/portal -config %s  (then open http://127.0.0.1:8080)", cfgPath, cfgPath)
	log.Printf("users: admin1/pass1 (all ok), drift/pass1 (site-2 rejects), nopr/pass1 (no AD principal)")

	sig := make(chan os.Signal, 1)
	signal.Notify(sig, os.Interrupt, syscall.SIGTERM)
	<-sig
}
